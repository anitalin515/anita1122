export function pickRandomThemeId(excludeId?: ThemeId): ThemeId {
  const candidates = excludeId
    ? THEME_LIST.filter((t) => t.id !== excludeId)
    : THEME_LIST;
  const idx = Math.floor(Math.random() * candidates.length);
  return candidates[idx].id;
}
